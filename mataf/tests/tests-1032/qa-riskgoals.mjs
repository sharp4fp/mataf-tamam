import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage();
await page.setViewport({ width: 1100, height: 1300 });
const errs = []; page.on('pageerror', e => errs.push(String(e)));
let pass = 0, fail = 0;
const ok = (c, n, d = '') => { if (c) { pass++; console.log('PASS ' + n); } else { fail++; console.log('FAIL ' + n + (d ? ' :: ' + d : '')); } };
const wait = (ms) => new Promise(r => setTimeout(r, ms));
const setSel = (sel, v) => page.evaluate((sel, v) => { const s = document.querySelector(sel); s.value = v; s.dispatchEvent(new Event('input', { bubbles: true })); s.dispatchEvent(new Event('change', { bubbles: true })); }, sel, v);
await page.goto('http://127.0.0.1:8099/?tab=portfolio', { waitUntil: 'networkidle2', timeout: 30000 });
await page.click('[data-action="demo"]'); await wait(800);
await page.evaluate(() => { const h = document.querySelector('[data-acc="riskgoals"]'); if (h.getAttribute('aria-expanded') !== 'true') h.click(); }); await wait(300);
const t = await page.evaluate(() => document.querySelector('#acc-body-riskgoals').innerText);
ok(/האם רמת הסיכון מתאימה למטרות הלקוח/.test(t) && /מקובץ המסלקה: יתרה/.test(t), 'title-and-auto-from-maslaka', t.slice(0, 200));
ok(await page.evaluate(() => !document.querySelector('[data-rg="equitySrc"]') && !!document.querySelector('select[data-rg="g0desc"]') && !!document.querySelector('select[data-rg="g0date"]') && !!document.querySelector('select[data-rg="resources"]') && !!document.querySelector('select[data-rg="liqDate"]')), 'selects-instead-of-text');
ok(await page.evaluate(() => !document.querySelector('[data-rg="g1desc"]')), 'second-goal-hidden-until-first');
await setSel('select[data-rg="g0desc"]', 'ירושה'); await wait(300);
ok(await page.evaluate(() => !!document.querySelector('[data-rg="g1desc"]') && !document.querySelector('[data-rg="g2desc"]')), 'second-goal-appears-after-first');
await setSel('select[data-rg="g1desc"]', 'אחר'); await wait(300);
ok(await page.evaluate(() => !!document.querySelector('input[data-rg="g1desc"]')), 'other-goal-opens-text');
await setSel('select[data-rg="willing"]', 'low'); await wait(300);
const flags = await page.evaluate(() => document.getElementById('rg-flags').innerText);
ok(/שמרן|נכונות לסיכון נמוכה/.test(flags) || /לבחינה|שאלה|חסר/.test(flags), 'flags-generated-with-auto-equity', flags.slice(0, 300));
const yrs = await page.evaluate(() => [...document.querySelectorAll('select[data-rg="g0date"] option')].map(o => o.textContent));
ok(yrs[1] === 'השנה' && yrs[2] === 'בעוד שנה' && yrs.length === 32, 'goal-date-as-years-ahead', yrs.slice(0, 4).join(','));
ok(errs.length === 0, 'no-page-errors', errs[0] || '');
console.log(`riskgoals: PASS=${pass} FAIL=${fail}`);
await browser.close();
process.exit(fail ? 1 : 0);
